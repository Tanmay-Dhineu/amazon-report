"""
Amazon Settlement (Payments) Report -> .xlsx

Settlement reports are generated by Amazon automatically at the end of every settlement
period - they cannot be requested. This script lists the ones Amazon has already created
and downloads them all into one workbook. Amazon keeps them for the last 90 days only.

Uses the same SP-API .env credentials as amazon_orders_report.py.
Run:  python amazon_settlement_report.py                          (last 90 days)
      python amazon_settlement_report.py 2026-10-01 2026-11-25    (settlements created in range)

Sheets:
  Summary      - one row per settlement: period, deposit date, total amount, and totals
                 of orders / refunds / fees etc.
  Transactions - every line of every settlement (order, refund, fee, adjustment, ...)
"""
import sys
from collections import defaultdict
from datetime import date, timedelta
from urllib.parse import urlencode

from openpyxl import Workbook

from amazon_inventory_report import download_document, to_value
from amazon_orders_report import MARKETPLACE, get_token, sp

REPORT_TYPE = "GET_V2_SETTLEMENT_REPORT_DATA_FLAT_FILE_V2"


def list_settlements(token, date_from, date_to):
    params = {
        "reportTypes": REPORT_TYPE,
        "processingStatuses": "DONE",
        "marketplaceIds": MARKETPLACE,
        "createdSince": f"{date_from}T00:00:00+05:30",
        "createdUntil": f"{date_to}T23:59:59+05:30",
        "pageSize": 100,
    }
    reports, path = [], "/reports/2021-06-30/reports?" + urlencode(params)
    while path:
        res = sp(token, "GET", path)
        reports += res.get("reports", [])
        nxt = res.get("nextToken")
        path = "/reports/2021-06-30/reports?" + urlencode({"nextToken": nxt}) if nxt else None
    return reports


def parse(text):
    lines = [l for l in text.splitlines() if l]
    headers = [h.strip() for h in lines[0].split("\t")]
    rows = []
    for line in lines[1:]:
        cells = line.split("\t")
        cells += [""] * (len(headers) - len(cells))
        rows.append(dict(zip(headers, cells)))
    return headers, rows


def main():
    if len(sys.argv) == 3:
        date_from, date_to = sys.argv[1], sys.argv[2]
    elif len(sys.argv) == 1:
        date_to = date.today().isoformat()
        date_from = (date.today() - timedelta(days=89)).isoformat()
    else:
        sys.exit("Usage: python amazon_settlement_report.py [YYYY-MM-DD YYYY-MM-DD]")

    token = get_token()
    reports = list_settlements(token, date_from, date_to)
    print(f"Found {len(reports)} settlement report(s) created {date_from} to {date_to}")
    if not reports:
        sys.exit("No settlement reports in this range (Amazon keeps only the last 90 days).")

    headers, all_rows, summaries = None, [], []
    for rep in sorted(reports, key=lambda r: r["createdTime"]):
        h, rows = parse(download_document(token, rep["reportDocumentId"]))
        headers = headers or h
        if not rows:
            continue

        # First row of each file is the settlement header (period, deposit, total)
        head, txns = rows[0], rows[1:]
        totals = defaultdict(float)
        for r in txns:
            try:
                totals[r.get("transaction-type") or "Other"] += float(r.get("amount") or 0)
            except ValueError:
                pass
        summaries.append((head, totals))
        all_rows += txns
        print(f"settlement {head.get('settlement-id')}: {len(txns)} lines, "
              f"total {head.get('total-amount')} {head.get('currency')}")

    wb = Workbook()

    # Summary sheet
    ws = wb.active
    ws.title = "Summary"
    types = sorted({t for _, tot in summaries for t in tot})
    ws.append(["settlement-id", "settlement-start-date", "settlement-end-date",
               "deposit-date", "currency", "total-amount", *types])
    for head, totals in sorted(summaries, key=lambda s: s[0].get("settlement-start-date", "")):
        ws.append([
            head.get("settlement-id"), head.get("settlement-start-date"),
            head.get("settlement-end-date"), head.get("deposit-date"), head.get("currency"),
            to_value("total-amount", head.get("total-amount", "")),
            *[round(totals[t], 2) if t in totals else None for t in types],
        ])
    ws.freeze_panes = "B2"

    # Transactions sheet
    ws = wb.create_sheet("Transactions")
    ws.append(headers)
    for r in all_rows:
        ws.append([to_value(h, r.get(h, "")) for h in headers])
    ws.freeze_panes = "A2"

    fmt = lambda d: f"{d[8:10]}-{d[5:7]}-{d[2:4]}"
    out = f"Amazon_Settlement-{fmt(date_from)}_to_{fmt(date_to)}.xlsx"
    wb.save(out)
    print(f"Saved {len(summaries)} settlements, {len(all_rows)} lines -> {out}")


if __name__ == "__main__":
    main()
